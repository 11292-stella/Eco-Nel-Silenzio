-- Un libro caricato (un PDF)
CREATE TABLE libro (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titolo            VARCHAR(255) NOT NULL,
    nome_file         VARCHAR(255) NOT NULL,
    numero_pagine     INT          NOT NULL DEFAULT 0,
    data_caricamento  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Le pagine del libro, con il testo estratto dal PDF
CREATE TABLE pagina (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libro_id  BIGINT NOT NULL REFERENCES libro(id) ON DELETE CASCADE,
    numero    INT    NOT NULL,
    testo     TEXT   NOT NULL,
    UNIQUE (libro_id, numero)
);

-- Le frasi di ogni pagina: è l'unità che la voce leggerà
CREATE TABLE frase (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagina_id  BIGINT NOT NULL REFERENCES pagina(id) ON DELETE CASCADE,
    numero     INT    NOT NULL,
    testo      TEXT   NOT NULL,
    UNIQUE (pagina_id, numero)
);